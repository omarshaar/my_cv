function applyLanguage(language) {
  const locale = translations[language] || translations.de;
  document.documentElement.lang = language;
  document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  document.title = locale.title;
  document.querySelector('meta[name="description"]').content = locale.description;
  document.querySelector("nav").setAttribute("aria-label", locale.navLabel);
  document.querySelector(".language-switcher").setAttribute("aria-label", locale.languageLabel);
  document.querySelector(".portrait-panel img").alt = locale.portraitAlt;
  toTop.setAttribute("aria-label", locale.toTop);

  Object.entries(bindings).forEach(([key, selector]) => {
    const element = document.querySelector(selector);
    if (element) {
      if (key === "download") {
        const icon = element.querySelector("span").outerHTML;
        element.innerHTML = `${locale[key]} ${icon}`;
      } else if (element.classList.contains("title-display") && locale[key].includes("<br>")) {
        const [lead, ...rest] = locale[key].split("<br>");
        element.innerHTML = `<span class="title-muted">${lead}</span> ${rest.join("<br>")}`;
      } else {
        element.innerHTML = locale[key];
      }
    }
  });

  document.querySelectorAll(".skill-card p").forEach((element, index) => {
    element.textContent = locale[skillDescriptionKeys[index]];
  });

  languageButtons.forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });

  try { localStorage.setItem("omar-shaar-language", language); } catch (_) {}
}

languageButtons.forEach((button) => button.addEventListener("click", () => applyLanguage(button.dataset.lang)));

